-- Esquema de ejemplo (ficticio) para probar er-diagram-skill sin una base de datos.
-- Mezcla estilos de Oracle a propósito: restricciones en línea, ALTER TABLE, COMMENT ON y FK compuestas.

CREATE TABLE GEN_ESTADOS (
  CODIGO      VARCHAR2(2)  NOT NULL,
  REFERENCIA  VARCHAR2(50) NOT NULL,
  DESCRIPCION VARCHAR2(200),
  CONSTRAINT GEN_ESTADOS_PK PRIMARY KEY (CODIGO, REFERENCIA)
);
COMMENT ON TABLE GEN_ESTADOS IS 'Catálogo de estados usado por todas las tablas (activo, inactivo, anulado...).';

CREATE TABLE GEN_MONEDAS (
  CODIGO VARCHAR2(3) PRIMARY KEY,
  NOMBRE VARCHAR2(60) NOT NULL,
  DECIMALES NUMBER(1) DEFAULT 2 NOT NULL
);
COMMENT ON TABLE GEN_MONEDAS IS 'Monedas ISO 4217 habilitadas.';

CREATE TABLE GEN_SUCURSALES (
  ID NUMBER(10) PRIMARY KEY,
  NOMBRE VARCHAR2(120) NOT NULL,
  CIUDAD VARCHAR2(80),
  ESTADO VARCHAR2(2) NOT NULL,
  ESTADO_REFERENCIA VARCHAR2(50) DEFAULT 'GEN_SUCURSALES' NOT NULL
);

CREATE TABLE CLI_CLIENTES (
  ID NUMBER(10) NOT NULL,
  ID_SUCURSAL NUMBER(10) NOT NULL REFERENCES GEN_SUCURSALES (ID),
  NOMBRE VARCHAR2(200) NOT NULL,
  CORREO VARCHAR2(120) UNIQUE,
  ESTADO VARCHAR2(2) NOT NULL,
  ESTADO_REFERENCIA VARCHAR2(50) NOT NULL,
  FECHA_ALTA DATE DEFAULT SYSDATE,
  CONSTRAINT CLI_CLIENTES_PK PRIMARY KEY (ID)
);
COMMENT ON TABLE CLI_CLIENTES IS 'Clientes de la tienda, asignados a una sucursal.';
COMMENT ON COLUMN CLI_CLIENTES.CORREO IS 'Correo de contacto; único por cliente.';

CREATE TABLE CLI_DIRECCIONES (
  ID_CLIENTE NUMBER(10) NOT NULL,
  LINEA NUMBER(3) NOT NULL,
  DIRECCION VARCHAR2(400) NOT NULL,
  ES_PRINCIPAL CHAR(1) DEFAULT 'N',
  CONSTRAINT CLI_DIR_PK PRIMARY KEY (ID_CLIENTE, LINEA),
  CONSTRAINT CLI_DIR_CLI_FK FOREIGN KEY (ID_CLIENTE) REFERENCES CLI_CLIENTES (ID) ON DELETE CASCADE
);

CREATE TABLE CLI_SEGMENTOS (
  ID NUMBER(5) PRIMARY KEY,
  NOMBRE VARCHAR2(60) NOT NULL
);
CREATE TABLE CLI_CLIENTES_SEGMENTOS (
  ID_CLIENTE NUMBER(10) NOT NULL,
  ID_SEGMENTO NUMBER(5) NOT NULL,
  CONSTRAINT CLI_CS_PK PRIMARY KEY (ID_CLIENTE, ID_SEGMENTO)
);
ALTER TABLE CLI_CLIENTES_SEGMENTOS ADD CONSTRAINT CLI_CS_CLI_FK FOREIGN KEY (ID_CLIENTE) REFERENCES CLI_CLIENTES (ID);
ALTER TABLE CLI_CLIENTES_SEGMENTOS ADD CONSTRAINT CLI_CS_SEG_FK FOREIGN KEY (ID_SEGMENTO) REFERENCES CLI_SEGMENTOS (ID);

CREATE TABLE INV_CATEGORIAS (
  ID NUMBER(5) PRIMARY KEY,
  ID_PADRE NUMBER(5) REFERENCES INV_CATEGORIAS (ID),
  NOMBRE VARCHAR2(80) NOT NULL
);
COMMENT ON TABLE INV_CATEGORIAS IS 'Árbol de categorías de producto (ID_PADRE apunta a la categoría superior).';

CREATE TABLE INV_PRODUCTOS (
  ID NUMBER(10) PRIMARY KEY,
  SKU VARCHAR2(30) NOT NULL UNIQUE,
  NOMBRE VARCHAR2(200) NOT NULL,
  ID_CATEGORIA NUMBER(5) NOT NULL REFERENCES INV_CATEGORIAS (ID),
  PRECIO NUMBER(18,2) NOT NULL,
  MONEDA VARCHAR2(3) NOT NULL REFERENCES GEN_MONEDAS (CODIGO),
  ESTADO VARCHAR2(2) NOT NULL,
  ESTADO_REFERENCIA VARCHAR2(50) NOT NULL
);

CREATE TABLE INV_EXISTENCIAS (
  ID_PRODUCTO NUMBER(10) NOT NULL,
  ID_SUCURSAL NUMBER(10) NOT NULL,
  CANTIDAD NUMBER(12,3) DEFAULT 0 NOT NULL,
  MINIMO NUMBER(12,3),
  CONSTRAINT INV_EXI_PK PRIMARY KEY (ID_PRODUCTO, ID_SUCURSAL),
  CONSTRAINT INV_EXI_PRO_FK FOREIGN KEY (ID_PRODUCTO) REFERENCES INV_PRODUCTOS (ID),
  CONSTRAINT INV_EXI_SUC_FK FOREIGN KEY (ID_SUCURSAL) REFERENCES GEN_SUCURSALES (ID)
);
COMMENT ON TABLE INV_EXISTENCIAS IS 'Existencias por producto y sucursal.';

CREATE TABLE INV_MOVIMIENTOS (
  ID NUMBER(12) PRIMARY KEY,
  ID_PRODUCTO NUMBER(10) NOT NULL,
  ID_SUCURSAL NUMBER(10) NOT NULL,
  TIPO VARCHAR2(10) NOT NULL,
  CANTIDAD NUMBER(12,3) NOT NULL,
  FECHA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT INV_MOV_EXI_FK FOREIGN KEY (ID_PRODUCTO, ID_SUCURSAL) REFERENCES INV_EXISTENCIAS (ID_PRODUCTO, ID_SUCURSAL)
);

CREATE TABLE VEN_PEDIDOS (
  ID NUMBER(12) PRIMARY KEY,
  ID_CLIENTE NUMBER(10) NOT NULL,
  ID_SUCURSAL NUMBER(10) NOT NULL,
  FECHA DATE DEFAULT SYSDATE NOT NULL,
  MONEDA VARCHAR2(3) NOT NULL,
  TOTAL NUMBER(18,2),
  ESTADO VARCHAR2(2) NOT NULL,
  ESTADO_REFERENCIA VARCHAR2(50) NOT NULL
);
ALTER TABLE VEN_PEDIDOS ADD (
  CONSTRAINT VEN_PED_CLI_FK FOREIGN KEY (ID_CLIENTE) REFERENCES CLI_CLIENTES (ID),
  CONSTRAINT VEN_PED_SUC_FK FOREIGN KEY (ID_SUCURSAL) REFERENCES GEN_SUCURSALES (ID),
  CONSTRAINT VEN_PED_MON_FK FOREIGN KEY (MONEDA) REFERENCES GEN_MONEDAS (CODIGO)
);
COMMENT ON TABLE VEN_PEDIDOS IS 'Cabecera de pedidos de venta.';

CREATE TABLE VEN_PEDIDOS_DETALLE (
  ID_PEDIDO NUMBER(12) NOT NULL,
  LINEA NUMBER(5) NOT NULL,
  ID_PRODUCTO NUMBER(10) NOT NULL,
  CANTIDAD NUMBER(12,3) NOT NULL,
  PRECIO_UNITARIO NUMBER(18,2) NOT NULL,
  DESCUENTO NUMBER(5,2) DEFAULT 0,
  CONSTRAINT VEN_PD_PK PRIMARY KEY (ID_PEDIDO, LINEA),
  CONSTRAINT VEN_PD_PED_FK FOREIGN KEY (ID_PEDIDO) REFERENCES VEN_PEDIDOS (ID) ON DELETE CASCADE,
  CONSTRAINT VEN_PD_PRO_FK FOREIGN KEY (ID_PRODUCTO) REFERENCES INV_PRODUCTOS (ID)
);

CREATE TABLE VEN_PAGOS (
  ID NUMBER(12) PRIMARY KEY,
  ID_PEDIDO NUMBER(12) NOT NULL REFERENCES VEN_PEDIDOS (ID),
  METODO VARCHAR2(20) NOT NULL,
  MONTO NUMBER(18,2) NOT NULL,
  FECHA DATE DEFAULT SYSDATE
);

CREATE TABLE VEN_FACTURAS (
  ID NUMBER(12) PRIMARY KEY,
  ID_PEDIDO NUMBER(12) NOT NULL UNIQUE REFERENCES VEN_PEDIDOS (ID),
  NUMERO VARCHAR2(30) NOT NULL UNIQUE,
  FECHA_EMISION DATE NOT NULL,
  ESTADO VARCHAR2(2) NOT NULL,
  ESTADO_REFERENCIA VARCHAR2(50) NOT NULL
);

CREATE TABLE SYS_BITACORA (
  ID NUMBER(15) PRIMARY KEY,
  USUARIO VARCHAR2(50) NOT NULL,
  ACCION VARCHAR2(200) NOT NULL,
  FECHA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE SYS_BITACORA IS 'Registro de acciones de los usuarios. Sin relaciones a propósito.';

