ALTER TABLE VEN_PEDIDOS ADD CONSTRAINT VEN_PED_EST_FK FOREIGN KEY (ESTADO, ESTADO_REFERENCIA) REFERENCES GEN_ESTADOS (CODIGO, REFERENCIA);
ALTER TABLE VEN_FACTURAS ADD CONSTRAINT VEN_FAC_EST_FK FOREIGN KEY (ESTADO, ESTADO_REFERENCIA) REFERENCES GEN_ESTADOS (CODIGO, REFERENCIA);

